// DEVELOPMENT ONLY. Real PostgreSQL tests, isolated temp table and temp sequence.
// Never executes the recovery SQL against public.businesses or production.
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
const require = createRequire(new URL("../lib/db/package.json", import.meta.url));
const { Pool } = require("pg");
if (!process.env.REPLIT_DEV_DOMAIN || process.env.REPLIT_DEPLOYMENT || process.env.NODE_ENV === "production") {
  throw new Error("Development workspace only");
}
const original = await readFile(new URL("../recovery/corvlio-existing-number.sql", import.meta.url), "utf8");
assert(!/\b(UPDATE|DELETE|ALTER|CREATE|DROP|TRUNCATE)\s+(TABLE|public\.|businesses)/i.test(original));
assert.equal((original.match(/INSERT INTO public\.businesses/g) ?? []).length, 1);
const sql = original
  .replaceAll("public.businesses", "pg_temp.recovery_businesses")
  .replace(/^BEGIN;$/m, "")
  .replace(/^COMMIT;$/m, "")
  .replace("'REPLACE_WITH_VERIFIED_PRODUCTION_CLERK_USER_ID'", "'user_verifiedProductionOwner'")
  .replace("'NOT VERIFIED'", "'PRODUCTION SESSION VERIFIED: pjmarkland08@gmail.com'");
const applySql = sql.replace("confirmation text := 'PREVIEW ONLY'", "confirmation text := 'INSERT CORVLIO +16624994839 FOR VERIFIED PRODUCTION USER'");
const pool = new Pool({ connectionString: process.env.DATABASE_URL });
const client = await pool.connect();
let passed = 0;
async function run(text) {
  const results = await client.query(text);
  return results.find(r => r.rows?.[0]?.recovery_review_result)?.rows[0].recovery_review_result;
}
async function test(name, work) {
  await client.query("SAVEPOINT scenario");
  try {
    await work();
    console.log(`PASS ${name}`);
    passed++;
  } finally {
    await client.query("ROLLBACK TO SAVEPOINT scenario");
  }
}
async function count() {
  return Number((await client.query("SELECT count(*) AS n FROM pg_temp.recovery_businesses")).rows[0].n);
}
async function mustRefuse(text, pattern) {
  await client.query("SAVEPOINT rejection");
  try {
    await assert.rejects(() => run(text), pattern);
  } finally {
    await client.query("ROLLBACK TO SAVEPOINT rejection");
  }
}
try {
  await client.query("BEGIN");
  await client.query("CREATE TEMP TABLE recovery_businesses (LIKE public.businesses INCLUDING ALL) ON COMMIT DROP");
  // LIKE copies a serial default referring to the REAL sequence: replace it before any inserts.
  await client.query("ALTER TABLE pg_temp.recovery_businesses ALTER COLUMN id DROP DEFAULT");
  await client.query("ALTER TABLE pg_temp.recovery_businesses ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY");
  await client.query(`INSERT INTO pg_temp.recovery_businesses (business_name, clerk_user_id, owner_email)
    VALUES ('Pjs company', 'user_olderOne', 'pjmarkland08@gmail.com'),
           ('Pjs company', 'user_olderTwo', 'pjmarkland08@gmail.com'),
           ('Other business', 'user_other', 'other@example.com')`);
  const baseline = (await client.query("SELECT to_jsonb(b) AS row FROM pg_temp.recovery_businesses b ORDER BY id")).rows;
  async function preserved() {
    const rows = (await client.query("SELECT to_jsonb(b) AS row FROM pg_temp.recovery_businesses b WHERE id<=3 ORDER BY id")).rows;
    assert.deepEqual(rows, baseline);
  }
  await test("copied snapshot exactly matches the current development source, including nulls and blanks", async () => {
    const source = (await client.query(`SELECT to_jsonb(b) - ARRAY[
      'id','clerk_user_id','created_at','updated_at','retell_phone_normalized'
    ] AS snapshot FROM public.businesses b WHERE id=5`)).rows[0].snapshot;
    const preview = await run(sql);
    const { clerk_user_id, ...copied } = preview.copied_fields_and_target_user;
    for (const key of ["agreements_accepted_at", "website_enrichment_attempted_at"]) {
      source[key] = new Date(source[key]).toISOString();
    }
    assert.deepEqual(copied, source);
  });
  await test("default preview cannot insert even with an eligible identity", async () => {
    const before = await count();
    const sequenceName = (await client.query("SELECT pg_get_serial_sequence('pg_temp.recovery_businesses','id') AS name")).rows[0].name;
    const sequenceBefore = (await client.query(`SELECT last_value FROM ${sequenceName}`)).rows[0].last_value;
    const result = await run(sql);
    assert.equal(result.mode, "preview");
    assert.equal(result.eligible, true);
    assert.equal(result.copied_fields_and_target_user.agent_name, null);
    assert.equal(result.copied_fields_and_target_user.provisioning_state, "pending");
    assert.equal(await count(), before);
    assert.equal((await client.query(`SELECT last_value FROM ${sequenceName}`)).rows[0].last_value, sequenceBefore);
    await preserved();
  });
  await test("exact snapshot inserts once; every copied field survives, generated phone is unique", async () => {
    const result = await run(applySql);
    assert.equal(await count(), 4);
    for (const [key, value] of Object.entries(result.copied_fields_and_target_user)) {
      if (key.endsWith("_at")) assert.equal(new Date(result.inserted_record[key]).toISOString(), value);
      else assert.deepEqual(result.inserted_record[key], value, key);
    }
    assert.equal(result.inserted_record.retell_phone_normalized, "16624994839");
    assert.equal((await client.query(`SELECT EXISTS (
      SELECT 1 FROM pg_locks WHERE relation='pg_temp.recovery_businesses'::regclass
      AND pid=pg_backend_pid() AND mode='ShareRowExclusiveLock' AND granted
    ) AS locked`)).rows[0].locked, true);
    await preserved();
  });
  await test("repeated confirmed run is an exact no-op", async () => {
    const first = await run(applySql);
    const second = await run(applySql);
    assert.equal(second.action, "already_claimed_no_write");
    assert.equal(second.existing_business_id, first.inserted_business_id);
    assert.equal(await count(), 4);
    await preserved();
  });
  await test("formatted number already assigned to another owner blocks preview and apply", async () => {
    await client.query(`INSERT INTO pg_temp.recovery_businesses (business_name,clerk_user_id,retell_phone_number)
      VALUES ('Someone else', 'user_someoneElse', '+1 (662) 499-4839')`);
    const preview = await run(sql);
    assert.equal(preview.eligible, false);
    assert(preview.blockers.some(b => b.includes("Number already")));
    await mustRefuse(applySql, /RECOVERY BLOCKED/);
    assert.equal(await count(), 4);
    await preserved();
  });
  await test("either older PJ owner identity is refused without modifying either business", async () => {
    for (const user of ["user_olderOne", "user_olderTwo"]) {
      await mustRefuse(applySql.replaceAll("user_verifiedProductionOwner", user), /Production login already owns a business/);
    }
    assert.equal(await count(), 3);
    await preserved();
  });
  await test("placeholder, known development identity, and missing attestation are refused", async () => {
    for (const text of [
      applySql.replaceAll("user_verifiedProductionOwner", "REPLACE_WITH_VERIFIED_PRODUCTION_CLERK_USER_ID"),
      applySql.replaceAll("user_verifiedProductionOwner", "user_3K2xZZqDscJ2qct9xlf9XBp3jR5"),
      applySql.replace("identity_attestation text := 'PRODUCTION SESSION VERIFIED: pjmarkland08@gmail.com'", "identity_attestation text := 'NOT VERIFIED'"),
    ]) await mustRefuse(text, /RECOVERY BLOCKED/);
    assert.equal(await count(), 3);
  });
  await test("unknown confirmation is refused, not treated as approval", async () => {
    await mustRefuse(sql.replace("confirmation text := 'PREVIEW ONLY'", "confirmation text := 'yes'"), /Unknown confirmation/);
    assert.equal(await count(), 3);
  });
  await test("later edits to recovered settings are not overwritten on rerun", async () => {
    await run(applySql);
    await client.query("UPDATE pg_temp.recovery_businesses SET business_hours='Changed by owner' WHERE clerk_user_id='user_verifiedProductionOwner'");
    await mustRefuse(applySql, /RECOVERY BLOCKED/);
    assert.equal((await client.query("SELECT business_hours FROM pg_temp.recovery_businesses WHERE clerk_user_id='user_verifiedProductionOwner'")).rows[0].business_hours, "Changed by owner");
    await preserved();
  });
  await test("database uniqueness independently rejects a formatted duplicate", async () => {
    await run(applySql);
    await client.query("SAVEPOINT duplicate");
    try {
      await assert.rejects(() => client.query(`INSERT INTO pg_temp.recovery_businesses (business_name,clerk_user_id,retell_phone_number)
        VALUES ('Duplicate', 'user_duplicate', '+1 (662) 499-4839')`), /duplicate key/);
    } finally {
      await client.query("ROLLBACK TO SAVEPOINT duplicate");
    }
    assert.equal(await count(), 4);
  });
  await test("missing unique phone protection fails closed", async () => {
    const index = (await client.query(`SELECT quote_ident(n.nspname)||'.'||quote_ident(c.relname) AS name
      FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid JOIN pg_namespace n ON n.oid=c.relnamespace
      WHERE i.indrelid='pg_temp.recovery_businesses'::regclass AND i.indisunique
      AND pg_get_indexdef(i.indexrelid) LIKE '%(retell_phone_normalized)%'`)).rows[0].name;
    await client.query(`DROP INDEX ${index}`);
    await mustRefuse(applySql, /unique phone\/owner indexes/);
    assert.equal(await count(), 3);
  });
  await test("changed generated normalization rule fails closed", async () => {
    await client.query("ALTER TABLE pg_temp.recovery_businesses DROP COLUMN retell_phone_normalized CASCADE");
    await client.query("ALTER TABLE pg_temp.recovery_businesses ADD COLUMN retell_phone_normalized text GENERATED ALWAYS AS (retell_phone_number) STORED");
    await client.query("CREATE UNIQUE INDEX recovery_changed_phone ON pg_temp.recovery_businesses (retell_phone_normalized)");
    await mustRefuse(applySql, /normalization rule differs/);
    assert.equal(await count(), 3);
  });
  console.log(`${passed} isolated PostgreSQL recovery tests passed. All temporary data rolled back.`);
} finally {
  await client.query("ROLLBACK");
  client.release();
  await pool.end();
}